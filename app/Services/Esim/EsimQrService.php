<?php

namespace App\Services\Esim;

use App\Models\Esim;
use App\Models\IntegrationLog;
use App\Models\ProviderOrder;
use chillerlan\QRCode\Common\EccLevel;
use chillerlan\QRCode\QRCode;
use chillerlan\QRCode\QROptions;
use chillerlan\QRCode\Output\QRGdImagePNG;
use Illuminate\Contracts\Filesystem\Filesystem;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\Crypt;
use Illuminate\Support\Facades\Storage;
use Throwable;

/**
 * Phase 9D — QR codes for purchased eSIMs.
 *
 * - The QR encodes ActivationPayload (LPA:1$<SM-DP+>$<matching ID>), built only
 *   from the activation details already stored (encrypted) on the eSIM. It never
 *   calls eSIM Go and never buys anything.
 * - The PNG is checked by decoding it again; a code that does not read back as
 *   the exact payload is never stored.
 * - The PNG is stored ENCRYPTED (APP_KEY) on the private "esim_qr" disk
 *   (storage/app/private/esim-qr, never served); esims.qr_code_path holds the
 *   file name. It is only streamed by the authorised admin QR route.
 * - Every outcome is logged in integration_logs (service "esim_qr") with the
 *   eSIM id and ICCID and a fixed, secret-free message — never the payload,
 *   matching ID or SM-DP+ address.
 * - Generating a QR code never changes the eSIM, provider order or order status.
 */
class EsimQrService
{
    public const DISK = 'esim_qr';

    public const STATE_GENERATED = 'generated';

    public const STATE_NOT_GENERATED = 'not_generated';

    public const STATE_FAILED = 'failed';

    public const STATE_UNAVAILABLE = 'unavailable';

    public const OP_GENERATED = 'qr_generated';

    public const OP_FAILED = 'qr_generation_failed';

    /** @throws InvalidActivationData */
    public function payload(Esim $esim): ActivationPayload
    {
        return ActivationPayload::fromEsim($esim);
    }

    /**
     * Create (or re-create) the QR code from the stored activation details.
     *
     * @param  string  $trigger  fulfilment | admin_regenerate (stored in the log)
     * @return array{ok: bool, message: string}
     */
    public function generate(Esim $esim, string $trigger): array
    {
        try {
            $payload = $this->payload($esim)->toString();
        } catch (InvalidActivationData $e) {
            return $this->failed($esim, $trigger, 'QR code not generated: '.$e->getMessage());
        }

        try {
            $png = $this->render($payload);
        } catch (Throwable) {
            return $this->failed($esim, $trigger, 'QR code not generated: the QR code library could not create the image.');
        }

        if (! $this->readsBackAs($png, $payload)) {
            return $this->failed($esim, $trigger, 'QR code not generated: the image did not read back as the activation code.');
        }

        $path = $esim->getKey().'.png.enc';
        try {
            $this->disk()->put($path, Crypt::encryptString($png));
            if (Crypt::decryptString((string) $this->disk()->get($path)) !== $png) {
                return $this->failed($esim, $trigger, 'QR code not generated: the saved image could not be read back from private storage.');
            }
        } catch (Throwable) {
            return $this->failed($esim, $trigger, 'QR code not generated: the image could not be saved to private storage.');
        }

        // Only the file name changes; the eSIM's status and the order are untouched.
        $esim->forceFill(['qr_code_path' => $path])->save();
        $this->log($esim, $trigger, true, 'QR code generated for eSIM '.$esim->iccid.'.');

        return ['ok' => true, 'message' => 'QR code generated for eSIM '.$esim->iccid.'.'];
    }

    /** Generate missing QR codes for a provider order's eSIMs. Never throws. */
    public function generateMissing(ProviderOrder $po): void
    {
        foreach ($po->esims()->whereNull('qr_code_path')->get() as $esim) {
            try {
                $this->generate($esim, 'fulfilment');
            } catch (Throwable) {
                // A QR problem must never affect fulfilment; it can be regenerated by an admin.
            }
        }
    }

    /** The decrypted PNG, or null when there is none (or it cannot be read). */
    public function image(Esim $esim): ?string
    {
        $path = (string) $esim->qr_code_path;
        if ($path === '' || ! preg_match('/^\d+\.png\.enc$/', $path)) {
            return null;
        }

        try {
            $disk = $this->disk();
            if (! $disk->exists($path)) {
                return null;
            }
            $png = Crypt::decryptString((string) $disk->get($path));
        } catch (Throwable) {
            return null;
        }

        return str_starts_with($png, "\x89PNG\r\n\x1a\n") ? $png : null;
    }

    /**
     * What to show for this eSIM's QR code. No provider call, no writes.
     *
     * @param  Collection<int, IntegrationLog>|null  $logs  the order's esim_qr log entries (newest first)
     * @return array{state: string, message: string}
     */
    public function status(Esim $esim, ?Collection $logs = null): array
    {
        try {
            $this->payload($esim);
        } catch (InvalidActivationData $e) {
            return ['state' => self::STATE_UNAVAILABLE, 'message' => 'Activation information is unavailable: '.$e->getMessage().' No QR code can be generated until eSIM Go provides it (use “Reconcile now” where available, or check the eSIM Go account).'];
        }

        $last = ($logs ?? IntegrationLog::query()->where('service', IntegrationLog::SERVICE_ESIM_QR)
            ->where('order_id', $esim->orderItem?->order_id)->orderByDesc('id')->get())
            ->first(fn ($log) => (int) data_get($log->request_body, 'esim_id') === (int) $esim->getKey());

        if ($esim->qr_code_path !== null && $this->image($esim) !== null) {
            return ['state' => self::STATE_GENERATED, 'message' => 'QR code generated'.($last?->operation === self::OP_GENERATED ? ' '.$last->created_at?->format('d M Y, H:i') : '').'.'];
        }
        if ($last?->operation === self::OP_FAILED) {
            return ['state' => self::STATE_FAILED, 'message' => (string) $last->error_message];
        }
        if ($esim->qr_code_path !== null) {
            return ['state' => self::STATE_FAILED, 'message' => 'The stored QR image is missing or unreadable. Regenerate it.'];
        }

        return ['state' => self::STATE_NOT_GENERATED, 'message' => 'No QR code has been generated yet.'];
    }

    private function render(string $payload): string
    {
        $options = new QROptions([
            'outputInterface' => QRGdImagePNG::class,
            'eccLevel' => EccLevel::M,       // ~15 % damage tolerance; keeps the code small for phone cameras
            'scale' => 10,                   // ~400 px for a typical activation code
            'addQuietzone' => true,
            'quietzoneSize' => 4,            // the 4-module margin the QR standard requires
            'outputBase64' => false,
            'imageTransparent' => false,
        ]);

        $png = (new QRCode($options))->render($payload);
        if (! is_string($png) || ! str_starts_with($png, "\x89PNG\r\n\x1a\n")) {
            throw new \RuntimeException('Not a PNG.');
        }

        return $png;
    }

    private function readsBackAs(string $png, string $payload): bool
    {
        try {
            return hash_equals($payload, (string) (new QRCode(new QROptions))->readFromBlob($png));
        } catch (Throwable) {
            return false;
        }
    }

    private function disk(): Filesystem
    {
        return Storage::disk(self::DISK);
    }

    /** @return array{ok: false, message: string} */
    private function failed(Esim $esim, string $trigger, string $message): array
    {
        $this->log($esim, $trigger, false, $message);

        return ['ok' => false, 'message' => $message];
    }

    private function log(Esim $esim, string $trigger, bool $success, string $message): void
    {
        IntegrationLog::query()->create([
            'service' => IntegrationLog::SERVICE_ESIM_QR,
            'operation' => $success ? self::OP_GENERATED : self::OP_FAILED,
            'success' => $success,
            'order_id' => $esim->orderItem?->order_id,
            'provider_order_id' => $esim->provider_order_id,
            'request_body' => ['esim_id' => $esim->getKey(), 'iccid' => $esim->iccid, 'trigger' => $trigger],
            'error_message' => $success ? null : mb_substr($message, 0, 500),
        ]);
    }
}
